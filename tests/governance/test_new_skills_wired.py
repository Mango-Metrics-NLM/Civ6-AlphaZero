"""The ``lua-bundle`` and ``review-threads`` skills say what they must, and are wired."""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
SKILLS = REPO_ROOT / ".claude" / "skills"


def _text(name: str) -> str:
    path = SKILLS / name / "SKILL.md"
    assert path.is_file(), f"missing {path}"
    return path.read_text(encoding="utf-8")


def test_lua_bundle_content() -> None:
    text = _text("lua-bundle")
    for needle in ("scripts/build_lua_bundle.py", "--check", "CIV6AZ_REQUIRE_LUA=1"):
        assert needle in text, needle
    assert "AlphaZeroMain.lua" in text
    low = text.lower()
    assert "module" in low and "never" in low


def test_review_threads_content() -> None:
    low = _text("review-threads").lower()
    for phrase in (
        "verify",
        "fails before",
        "resolve",
        "two review rounds",
        "security",
        "never approve",
        "merge",
    ):
        assert phrase in low, phrase
    assert "against the code" in low
    assert "commit" in low and "test" in low
    assert "open" in low and "user" in low


def test_developer_and_prepr_reference_both_skills() -> None:
    for path in (
        REPO_ROOT / ".claude" / "agents" / "sdlc-developer.md",
        SKILLS / "pre-pr-handoff" / "SKILL.md",
    ):
        text = path.read_text(encoding="utf-8")
        for name in ("lua-bundle", "review-threads"):
            assert name in text, f"{path.name} does not reference {name}"


def test_validate_claude_agents_still_passes() -> None:
    proc = subprocess.run(
        [sys.executable, str(REPO_ROOT / "scripts" / "validate_claude_agents.py")],
        capture_output=True,
        text=True,
        check=False,
        cwd=REPO_ROOT,
    )
    assert proc.returncode == 0, proc.stderr


def test_review_threads_uses_only_routes_the_guard_allows() -> None:
    """The guard denies GraphQL and write-capable ``gh api``; the skill names the MCP tools."""
    text = _text("review-threads")
    for tool in ("pull_request_read", "get_review_comments", "add_reply_to_pull_request_comment"):
        assert tool in text, tool
    assert "resolve_review_thread" in text
    low = text.lower()
    assert "no tool can resolve" in low and "leave the thread open" in low
    assert "harness instructions" in low, "the footer must be attributed to the harness"
    assert "the repository's replies use" not in low
    assert "_generated by [claude code]" not in low
