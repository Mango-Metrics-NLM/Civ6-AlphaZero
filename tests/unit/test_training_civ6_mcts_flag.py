"""``--mcts {civ6,gumbel}`` reaches both self-play and evaluation.

``TrainingConfig.use_gumbel_mcts`` existed, but nothing on the command line set
it, and ``evaluate_against_random`` ignored it: it was hard-coded to PUCT, so a
Gumbel run was generated by one search and scored by another. The flag defaults
to ``civ6`` so a run that never passes it is byte-identical to before.

Negative controls performed when this file was written (each reverted):

* ``use_gumbel_mcts=args.mcts == "gumbel"`` removed from ``main`` ->
  ``test_gumbel_flag_sets_use_gumbel_mcts`` fails;
* the ``if config.use_gumbel_mcts`` branch removed from ``evaluate_against_random``
  -> ``test_eval_uses_gumbel_when_configured`` fails (``Civ6MCTS`` constructed instead).
"""

from __future__ import annotations

from typing import Any
from unittest.mock import MagicMock, patch

import numpy as np
import pytest

from alpha_zero import training_civ6
from alpha_zero.training_civ6 import TrainingConfig, evaluate_against_random


def _run_main(argv: list[str]) -> TrainingConfig:
    captured: dict[str, Any] = {}

    def fake_train(config: TrainingConfig, dry_run: bool = False) -> None:
        captured["config"] = config

    with (
        patch.object(training_civ6, "train", fake_train),
        patch("sys.argv", ["training_civ6", *argv]),
    ):
        training_civ6.main()
    config = captured["config"]
    assert isinstance(config, TrainingConfig)
    return config


class TestArgparseRoundTrip:
    def test_default_is_puct(self) -> None:
        assert _run_main([]).use_gumbel_mcts is False

    def test_explicit_civ6_is_puct(self) -> None:
        assert _run_main(["--mcts", "civ6"]).use_gumbel_mcts is False

    def test_gumbel_flag_sets_use_gumbel_mcts(self) -> None:
        assert _run_main(["--mcts", "gumbel"]).use_gumbel_mcts is True

    def test_unknown_variant_is_rejected(self) -> None:
        with pytest.raises(SystemExit):
            _run_main(["--mcts", "muzero"])


def _mock_search_class() -> MagicMock:
    """A search double that plays the first legal action, so games terminate."""
    instance = MagicMock()

    def search(env: Any, add_noise: bool = False) -> tuple[np.ndarray, float]:
        mask = env.get_valid_actions().astype(np.float32)
        return mask / max(mask.sum(), 1.0), 0.0

    instance.search.side_effect = search
    instance.select_action.side_effect = lambda probs, temperature=0.0: int(np.argmax(probs))
    cls = MagicMock(return_value=instance)
    return cls


def _config(use_gumbel: bool) -> TrainingConfig:
    return TrainingConfig(
        board_size=6,
        max_turns=2,
        num_simulations=2,
        gumbel_num_simulations=4,
        gumbel_num_sampled_actions=2,
        use_gumbel_mcts=use_gumbel,
        device="cpu",
        seed=11,
    )


class TestEvaluationUsesTheConfiguredSearch:
    def test_eval_uses_gumbel_when_configured(self) -> None:
        gumbel_cls = _mock_search_class()
        puct_cls = _mock_search_class()
        with (
            patch.object(training_civ6, "GumbelMCTS", gumbel_cls),
            patch.object(training_civ6, "Civ6MCTS", puct_cls),
        ):
            rate = evaluate_against_random(MagicMock(), _config(use_gumbel=True), num_games=1)
        assert gumbel_cls.called
        assert not puct_cls.called
        assert 0.0 <= rate <= 1.0
        # The Gumbel config carries the derived evaluation search seed.
        gumbel_config = gumbel_cls.call_args.args[1]
        assert gumbel_config.seed is not None

    def test_eval_uses_puct_by_default(self) -> None:
        gumbel_cls = _mock_search_class()
        puct_cls = _mock_search_class()
        with (
            patch.object(training_civ6, "GumbelMCTS", gumbel_cls),
            patch.object(training_civ6, "Civ6MCTS", puct_cls),
        ):
            evaluate_against_random(MagicMock(), _config(use_gumbel=False), num_games=1)
        assert puct_cls.called
        assert not gumbel_cls.called
        # Unchanged legacy budget: half of num_simulations.
        assert puct_cls.call_args.args[1].num_simulations == 1


class TestScoreRateLogLine:
    def test_logs_a_parseable_score_rate_line(self, caplog: pytest.LogCaptureFixture) -> None:
        import importlib.util
        import logging
        from pathlib import Path

        puct_cls = _mock_search_class()
        with (
            patch.object(training_civ6, "Civ6MCTS", puct_cls),
            caplog.at_level(logging.INFO, logger="alpha_zero.training_civ6"),
        ):
            evaluate_against_random(MagicMock(), _config(use_gumbel=False), num_games=2)
        lines = [r.getMessage() for r in caplog.records]
        score_lines = [m for m in lines if m.startswith("Eval score rate vs random:")]
        assert len(score_lines) == 1

        # The log summariser must read exactly what the trainer writes.
        script = Path(__file__).resolve().parents[2] / "scripts" / "summarize_training_log.py"
        spec = importlib.util.spec_from_file_location("summarize_training_log", script)
        assert spec is not None and spec.loader is not None
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        match = module.RE_SCORERATE.search(score_lines[0])
        assert match is not None, score_lines[0]
        assert int(match.group(6)) == 2
