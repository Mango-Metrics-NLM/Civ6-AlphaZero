def verify(release: fx.Release, *, api: Any = None) -> tuple[int, str]:
    """Run the CLI on the release's bundle; ``(exit code, stdout + stderr)``."""
    import contextlib
    import io

    out, err = io.StringIO(), io.StringIO()
    with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
        code = vre.main(
            [
                str(release.bundle_dir / vre.BUNDLE_FILE),
                "--repo-root",
                str(release.repo.path),
                "--repo",
                fx.REPO,
            ],
            api=api or fx.fake_api(release.rc_sha),
            env={},
        )
    return code, out.getvalue() + err.getvalue()


def _json(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8"))


def _dump(path: Path, data: Any) -> None:
    path.write_text(json.dumps(data, indent=2), encoding="utf-8", newline="\n")


