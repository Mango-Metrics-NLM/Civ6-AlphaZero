class TestScope:
    @pytest.mark.parametrize(
        ("event", "base", "head", "applies"),
        [
            ("pull_request", "main", "qa", True),
            ("pull_request", "main", "release/x", True),
            ("pull_request", "dev", "feature/x", False),
            ("pull_request", "qa", "dev", False),
            ("pull_request", "main", "hotfix/urgent", False),
            ("push", "", "", False),
        ],
    )
    def test_scope(self, event: str, base: str, head: str, applies: bool) -> None:
        assert vre.scope(event, base, head)[0] is applies

    def test_the_job_reports_na_on_a_non_main_base(
        self, tmp_path: Path, capsys: pytest.CaptureFixture[str]
    ) -> None:
        output = tmp_path / "out"
        env = {
            "EVENT_NAME": "pull_request",
            "BASE_REF": "dev",
            "HEAD_REF": "feature/x",
            "GITHUB_OUTPUT": str(output),
        }
        assert vre.main(["--scope"], env=env) == vre.EXIT_PASS
        assert "n/a" in capsys.readouterr().out
        assert output.read_text(encoding="utf-8") == "applies=false\n"

    def test_a_release_pr_applies(self, tmp_path: Path) -> None:
        output = tmp_path / "out"
        env = {
            "EVENT_NAME": "pull_request",
            "BASE_REF": "main",
            "HEAD_REF": "qa",
            "GITHUB_OUTPUT": str(output),
        }
        assert vre.main(["--scope"], env=env) == vre.EXIT_PASS
        assert output.read_text(encoding="utf-8") == "applies=true\n"


def _job() -> dict[str, Any]:
    jobs = yaml.safe_load(CI_YML.read_text(encoding="utf-8"))["jobs"]
    (job,) = [j for j in jobs.values() if j.get("name") == "Release Evidence"]
    return dict(job)


class TestCiJob:
    def test_the_job_always_runs_and_blocks(self) -> None:
        job = _job()
        assert "if" not in job  # a skipped required check is a merge nobody can make
        assert not job.get("continue-on-error", False)

    def test_the_checkout_has_full_history_and_no_credentials(self) -> None:
        checkout = _job()["steps"][0]
        assert checkout["uses"].startswith("actions/checkout@")
        assert checkout["with"]["fetch-depth"] == 0
        assert checkout["with"]["persist-credentials"] is False

    def test_refs_come_from_env_never_from_run(self) -> None:
        steps = _job()["steps"]
        for step in steps:
            assert "${{" not in str(step.get("run", "")), step.get("name")
        (scope_step,) = [s for s in steps if "--scope" in str(s.get("run", ""))]
        assert scope_step["env"]["BASE_REF"] == "${{ github.base_ref }}"
        assert scope_step["env"]["HEAD_REF"] == "${{ github.head_ref }}"
        assert scope_step["env"]["EVENT_NAME"] == "${{ github.event_name }}"

    def test_every_step_after_scope_is_gated_on_it(self) -> None:
        steps = _job()["steps"]
        index = next(i for i, s in enumerate(steps) if "--scope" in str(s.get("run", "")))
        assert steps[index]["id"] == "scope"
        for step in steps[index + 1 :]:
            assert step.get("if") == "steps.scope.outputs.applies == 'true'", step.get("name")

    def test_the_verifier_runs_without_weakening_flags(self) -> None:
        runs = [str(s.get("run", "")) for s in _job()["steps"]]
        (verify_run,) = [r for r in runs if "verify_release_evidence" in r and "--scope" not in r]
        assert re.search(r"\s--(?!repo\b)", verify_run) is None, verify_run

    def test_permissions_are_read_only(self) -> None:
        perms = _job()["permissions"]
        assert perms == {"contents": "read", "checks": "read", "pull-requests": "read"}
