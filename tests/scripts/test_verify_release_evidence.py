class TestFreshness:
    def test_a_play_path_change_since_the_run_fails(self, tmp_path: Path) -> None:
        release = fx.make_release(
            tmp_path, after_run={"alpha_zero/core/mcts/base.py": "BASE = 2\n"}
        )
        code, out = verify(release)
        assert code == vre.EXIT_FAIL
        assert "play path changed" in out and "alpha_zero/core/mcts/base.py" in out

    def test_a_change_off_the_play_path_passes(self, tmp_path: Path) -> None:
        release = fx.make_release(tmp_path, after_run={"alpha_zero/unrelated.py": "X = 2\n"})
        assert release.run_sha != release.rc_sha
        assert verify(release)[0] == vre.EXIT_PASS

    def test_a_run_sha_that_is_not_an_ancestor_of_the_rc_fails(self, tmp_path: Path) -> None:
        release = fx.make_release(tmp_path)
        repo = release.repo
        repo.checkout("side", release.run_sha + "~0")
        side = repo.commit("side work")
        repo.checkout("main")
        for run in release.bundle["runs"]:
            run["git_sha"] = side
            path = release.bundle_dir / run["run_json"]["path"]
            record = _json(path)
            record["sha"] = side
            _dump(path, record)
            fx.rehash(release.bundle_dir, run["run_json"])
        release.save()
        code, out = verify(release)
        assert code == vre.EXIT_FAIL
        assert "is not an ancestor of rc_sha" in out

    def test_an_mcts_override_fails(self, tmp_path: Path) -> None:
        release = fx.make_release(tmp_path, [fx.RunSpec(env_var_names=["MCTS_C_VISIT", "PATH"])])
        assert release.bundle["runs"][0]["verdict"]["verdict"] == "VOID"
        code, out = verify(release)
        assert code == vre.EXIT_FAIL
        assert "MCTS_* overrides ['MCTS_C_VISIT']" in out

    def test_a_protocol_hash_mismatch_fails(self, tmp_path: Path) -> None:
        text = fx.EVALUATION_TEXT
        edited = text.replace("The first matching row wins.", "The last matching row wins.", 1)
        assert edited != text
        release = fx.make_release(tmp_path, code={"docs/EVALUATION.md": edited})
        code, out = verify(release)
        assert code == vre.EXIT_FAIL
        assert "protocol_sha256" in out and "section 7.1" in out

    def test_a_wrong_release_version_fails(self, tmp_path: Path) -> None:
        release = fx.make_release(
            tmp_path, code={"pyproject.toml": fx.PYPROJECT.replace("2.1.0", "2.2.0")}
        )
        code, out = verify(release)
        assert code == vre.EXIT_FAIL
        assert "pyproject.toml" in out

    def test_a_tag_on_another_commit_fails(self, tmp_path: Path) -> None:
        release = fx.make_release(tmp_path)
        release.repo.git("tag", "-f", "-a", fx.RC_TAG, "-m", "moved", "HEAD")
        code, out = verify(release)
        assert code == vre.EXIT_FAIL
        assert "does not point at rc_sha" in out


